"""Deterministic Jinja agent skill generation and drift detection."""

from __future__ import annotations

from typing import TYPE_CHECKING, Any

from tasknest.errors import ConfigError, ToolError

if TYPE_CHECKING:
    from pathlib import Path

    from tasknest.discovery import TaskRegistry
    from tasknest.task import TaskDefinition

_COMMA_SEP = ", "
_UTF8 = "utf-8"
GENERATED_MARKER = "<!-- Generated by tasknest; do not edit by hand. -->"

DEFAULT_SKILL_TEMPLATE = """<!-- Generated by tasknest; do not edit by hand. -->
# Project Tools Skill

Run repository tasks with `{{ command }}`.

## Tasks
{% for task in tasks %}
### `{{ task.cli_command }}` (`{{ task.name }}`)
{% if task.description %}{{ task.description }}
{% endif %}{% if task.marks %}- Marks: {{ task.marks }}
{% endif %}{% if task.requires %}- Requires: {{ task.requires }}
{% endif %}{% if task.depends %}- Depends: {{ task.depends }}
{% endif %}{% if task.persistent %}- Persistent: true
{% endif %}{% if task.options %}- Options: {{ task.options }}
{% endif %}{% endfor %}"""


def _load_jinja_environment() -> Any:
    try:
        import jinja2
    except ModuleNotFoundError as exc:
        raise ConfigError(
            "Jinja2 is required for skill generation; install 'tasknest[skill]'."
        ) from exc
    return jinja2.Environment(
        autoescape=jinja2.select_autoescape(),
        keep_trailing_newline=True,
    )


def _format_task_entry(task: TaskDefinition, command: str) -> dict[str, str]:
    cli_path = " ".join(task.cli_path)
    deps = _COMMA_SEP.join(d if isinstance(d, str) else d.name for d in task.depends)
    opts = _COMMA_SEP.join(f"--{opt.cli_name} <{opt.format_type()}>" for opt in task.options)
    return {
        "name": task.name,
        "cli_path": cli_path,
        "cli_command": f"{command} run {cli_path}",
        "description": task.description.strip(),
        "marks": _COMMA_SEP.join(task.marks),
        "requires": _COMMA_SEP.join(task.requires),
        "depends": deps,
        "persistent": "true" if task.persistent else "",
        "options": opts,
    }


def _resolve_template_source(registry: TaskRegistry, template_path: Path | None) -> str:
    configured = template_path
    if configured is None and registry.config.skill.template is not None:
        configured = registry.config.repo_root / registry.config.skill.template
    if configured is None:
        return DEFAULT_SKILL_TEMPLATE
    if not configured.is_file():
        raise ConfigError(f"Skill template not found: {configured}")
    return configured.read_text(encoding=_UTF8)


def render_skill(registry: TaskRegistry, *, template_path: Path | None = None) -> str:
    """Render deterministic skill documentation from discovered task metadata."""
    env = _load_jinja_environment()
    source = _resolve_template_source(registry, template_path)
    command = registry.config.skill.command
    entries = [_format_task_entry(task, command) for task in registry.ordered_tasks()]
    rendered = str(env.from_string(source).render(command=command, tasks=entries))
    return rendered if rendered.endswith("\n") else f"{rendered}\n"


def resolve_skill_output(registry: TaskRegistry, output_path: Path | None = None) -> Path:
    """Resolve the target SKILL.md path relative to repo_root."""
    if output_path is not None:
        return (
            output_path if output_path.is_absolute() else (registry.config.repo_root / output_path)
        )
    return registry.config.repo_root / registry.config.skill.output


def check_skill(
    registry: TaskRegistry,
    *,
    output_path: Path | None = None,
    template_path: Path | None = None,
) -> bool:
    """Check whether the skill file matches fresh deterministic rendering."""
    target = resolve_skill_output(registry, output_path)
    if not target.is_file():
        return False
    expected = render_skill(registry, template_path=template_path)
    return target.read_text(encoding=_UTF8) == expected


def write_skill(
    registry: TaskRegistry,
    *,
    output_path: Path | None = None,
    template_path: Path | None = None,
    force: bool = False,
) -> Path:
    """Write generated skill file while protecting manually maintained files."""
    target = resolve_skill_output(registry, output_path)
    if target.exists() and not force:
        existing = target.read_text(encoding=_UTF8)
        if GENERATED_MARKER not in existing:
            raise ToolError(
                f"Refusing to overwrite manual skill file {target} without force=True (--force)."
            )
    rendered = render_skill(registry, template_path=template_path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(rendered, encoding=_UTF8)
    return target
